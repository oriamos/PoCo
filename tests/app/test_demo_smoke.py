"""Smoke test for the documented demo (TRY_DEMO.md): the committed synthetic slide, end to end through the API.

The demo slide is resources/dataset_files/test/test_img.tif, generated by make_test_img.py. It is synthetic, so this
test checks the flow (import -> channel mapping -> counting region -> detection -> counts -> export), not any
scientific result: it only asserts that the pipeline finishes and produces counts and an export bundle.
"""
import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

pytest.importorskip("bigfish")
pytest.importorskip("polony_app.detection.pipeline")

from fakes import counting, rect, wait_job  # noqa: E402
from polony_app.api.main import create_app  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
DEMO = REPO / "resources" / "dataset_files" / "test" / "test_img.tif"
TRUTH = DEMO.with_name("test_img.truth.json")
DETECT = {
    "red": {"spot_radius_px": 2.5, "minimum_distance_px": 5, "threshold": 20, "background": {"method": "gaussian_subtract", "sigma_px": 15}},
    "green": {"spot_radius_px": 2.5, "minimum_distance_px": 5, "threshold": 20, "background": {"method": "gaussian_subtract", "sigma_px": 15}},
}


def test_demo_file_is_the_documented_synthetic_example():
    truth = json.loads(TRUTH.read_text())
    assert truth["synthetic"] is True
    assert truth["pages"]["0"]["role"] == "red" and truth["pages"]["1"]["role"] == "green"
    assert DEMO.stat().st_size > 0


def test_demo_path_import_map_detect_export(tmp_path):
    with TestClient(create_app(tmp_path / "demo-data")) as c:
        with open(DEMO, "rb") as f:
            a = c.post("/api/analyses", files=[("files", (DEMO.name, f, "image/tiff"))]).json()
        aid = a["id"]
        # the file name never confirms a channel role on its own
        assert a["status"] == "needs_channel_mapping"
        c.put(f"/api/analyses/{aid}/channels", json={"mapping": [{"index": 0, "role": "red"}, {"index": 1, "role": "green"}]})
        w, h = a["image"]["width"], a["image"]["height"]
        c.put(f"/api/analyses/{aid}/regions", json={"regions": [counting("c1", rect(5, 5, w - 5, h - 5)).model_dump(mode="json")]})
        j = wait_job(c, c.post(f"/api/analyses/{aid}/detect", json=DETECT).json()["id"], 300)
        assert j["status"] == "done", j
        counts = c.get(f"/api/analyses/{aid}/counts").json()["slide"]
        assert sum(counts[k] for k in ("red_only", "green_only", "yellow", "uncertain")) > 0
        z = c.get(f"/api/analyses/{aid}/export", params={"kind": "bundle"})
        assert z.status_code == 200 and z.content[:2] == b"PK"


def test_demo_grid_detect_and_save_writes_the_documented_files(tmp_path):
    """TRY_DEMO.md steps 2-7: open in place, map, generate the grid of the demo slide, detect, Save next to the scan."""
    import shutil

    scan_dir = tmp_path / "input"
    scan_dir.mkdir()
    scan = scan_dir / "test_img.tif"
    shutil.copyfile(DEMO, scan)
    grid = json.loads(TRUTH.read_text())["grid"]
    with TestClient(create_app(tmp_path / "demo-data" / "app")) as c:
        r = c.post("/api/analyses/open-path", json={"path": str(scan)})
        assert r.status_code == 200, r.text
        aid = r.json()["id"]
        c.put(f"/api/analyses/{aid}/channels", json={"mapping": [{"index": 0, "role": "red"}, {"index": 1, "role": "green"}]})
        # the lab template has fields 1..24, so the 4 x 7 grid of the slide is used as 4 columns x 6 rows
        spec = {"rows": 24 // grid["n_cols"], "cols": grid["n_cols"], "cell_w": grid["spacing"], "cell_h": grid["spacing"],
                "origin_x": grid["xs"][0], "origin_y": grid["ys"][0]}
        g = c.put(f"/api/analyses/{aid}/grid", json={"grid": spec})
        assert g.status_code == 200, g.text
        j = wait_job(c, c.post(f"/api/analyses/{aid}/detect", json=DETECT).json()["id"], 300)
        assert j["status"] == "done", j
        s = c.post(f"/api/analyses/{aid}/save-slide", json={"selections": [{"classes": ["red", "green", "yellow"]}]})
        assert s.status_code == 200, s.text
    assert (scan_dir / "test_img_labeled.tif").is_file()
    assert (scan_dir / "test_img.csv").is_file()
    assert (scan_dir / "experiment_counts.csv").is_file()
